import { useState } from 'react';
import { AlertTriangle, CheckCircle2, Send, Cpu, Search, Users, BedDouble, Undo2, MessageSquare, Clock } from 'lucide-react';
import clsx from 'clsx';
import { PageHeader, StatCard, SectionCard, Tabs, StatusBadge, AppButton, Modal, useToast, t } from '@shared-ui';
import type { AssignmentProposalStatus } from '@campusstay/constants';

/**
 * Review / Adjust Room Assignment Proposal (Staff) — docs/BUSINESS_FLOWS.md F2.
 * Engine (actor System) đã chạy: chốt ghép bạn cùng phòng → xếp phòng → phát hiện xung đột.
 * Staff xử lý từng dòng có cảnh báo rồi gửi Manager duyệt.
 */

type Conflict = 'DOUBLE_BED' | 'SPLIT_PAIR' | 'GENDER' | 'OVER_CAPACITY';

interface Row {
  id: string;
  name: string;
  gender: 'Male' | 'Female';
  roomType: string;
  group?: string;
  bed: string;
  conflict?: Conflict;
  adjusted?: string;
}

const CONFLICT_LABEL: Record<Conflict, string> = {
  DOUBLE_BED: t('Bed assigned twice'),
  SPLIT_PAIR: t('Roommate pair split'),
  GENDER: t('Wrong gender zone'),
  OVER_CAPACITY: t('Room over capacity'),
};

const ROWS: Row[] = [
  { id: 'SE172211', name: 'Võ Thị Bảo Ngọc', gender: 'Female', roomType: t('4-bed air-conditioned'), group: t('Pair #A17'), bed: 'C305-G1', conflict: 'SPLIT_PAIR' },
  { id: 'SE171234', name: 'Nguyễn Thị Mai Anh', gender: 'Female', roomType: t('4-bed air-conditioned'), group: t('Pair #A17'), bed: 'A204-G1' },
  { id: 'SE190455', name: 'Đỗ Minh Quân', gender: 'Male', roomType: t('4-bed air-conditioned'), bed: 'B210-G4', conflict: 'DOUBLE_BED' },
  { id: 'SE190888', name: 'Nguyễn Hoàng Long', gender: 'Male', roomType: t('4-bed air-conditioned'), bed: 'B210-G4' },
  { id: 'GD190087', name: 'Phan Thùy Dung', gender: 'Female', roomType: t('4-bed with fan'), bed: 'B118-G2', conflict: 'GENDER' },
  { id: 'IA171876', name: 'Đặng Minh Thư', gender: 'Female', roomType: t('4-bed air-conditioned'), bed: 'A115-G5', conflict: 'OVER_CAPACITY' },
  { id: 'SE190112', name: 'Lê Thị Hồng Nhung', gender: 'Female', roomType: t('4-bed air-conditioned'), bed: 'C305-G2' },
  { id: 'SE170321', name: 'Hồ Tấn Phát', gender: 'Male', roomType: t('4-bed air-conditioned'), bed: 'D402-G1' },
  { id: 'BA173001', name: 'Huỳnh Gia Hân', gender: 'Female', roomType: t('4-bed air-conditioned'), bed: 'C210-G3' },
];

const FREE_BEDS: Record<'Male' | 'Female', string[]> = {
  Female: ['A204-G2', 'A115-G3', 'A220-G4', 'C301-G1', 'C301-G2'],
  Male: ['B210-G3', 'B305-G1', 'D402-G3', 'D118-G2'],
};

const ROUND2 = [
  { id: 'SS190234', name: 'Mai Khánh Vy', roomType: t('2-bed'), reason: t('No 2-bed rooms left'), accepted: true },
  { id: 'BA190012', name: 'Lý Thanh Trúc', roomType: t('6-bed'), reason: t('No 6-bed rooms left'), accepted: true },
  { id: 'SE191020', name: 'Phạm Quốc Huy', roomType: t('2-bed'), reason: t('No 2-bed rooms left'), accepted: false },
];

type TabKey = 'proposal' | 'round2';

export function StaffAssignmentPage() {
  const { show, toastNode } = useToast();
  const [rows, setRows] = useState(ROWS);
  const [tab, setTab] = useState<TabKey>('proposal');
  const [onlyConflicts, setOnlyConflicts] = useState(true);
  const [query, setQuery] = useState('');
  const [status, setStatus] = useState<AssignmentProposalStatus | 'DRAFT'>('DRAFT');
  const [sendOpen, setSendOpen] = useState(false);
  const [note, setNote] = useState('');

  const open = rows.filter((r) => r.conflict && !r.adjusted);
  const visible = rows.filter((r) => (!onlyConflicts || r.conflict) && (!query || `${r.name} ${r.id} ${r.bed}`.toLowerCase().includes(query.toLowerCase())));

  const adjust = (id: string, bed: string) => {
    setRows((all) => all.map((r) => (r.id === id ? { ...r, adjusted: bed } : r)));
    show(t('Moved {0} to {1} — the system is re-checking conflicts', { 0: id, 1: bed }), 'info');
  };
  const undo = (id: string) => setRows((all) => all.map((r) => (r.id === id ? { ...r, adjusted: undefined } : r)));

  return (
    <div className="space-y-6">
      <PageHeader
        title={t('Allocation')}
        description={t('Review & adjust the proposal generated by the allocation algorithm, then send it to the manager for approval')}
        actions={
          <AppButton size="sm" disabled={status !== 'DRAFT' || open.length > 0} leftIcon={<Send className="w-4 h-4" />} onClick={() => setSendOpen(true)}>
            {t('Send to manager')}
          </AppButton>
        }
      />

      <div className="flex flex-col md:flex-row md:items-center gap-3 p-4 rounded-xl bg-surface-sunken border border-blue-100 text-xs text-ink">
        <Cpu className="w-5 h-5 shrink-0" />
        <span className="flex-1">
          {t('Proposal')} <strong>BR-SP27-02</strong> {t('· Engine run 25/11/2026 03:00 · 342 allocations · 41/44 roommate pairs kept.')}
        </span>
        <StatusBadge status={status} customLabel={status === 'DRAFT' ? t('Waiting for staff review') : undefined} />
      </div>

      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <StatCard label={t('Allocations in proposal')} value="342" icon={BedDouble} tone="navy" />
        <StatCard label={t('Unresolved conflicts')} value={open.length} icon={AlertTriangle} tone={open.length ? 'rose' : 'emerald'} />
        <StatCard label={t('Adjusted')} value={rows.filter((r) => r.adjusted).length} icon={CheckCircle2} tone="emerald" />
        <StatCard label={t('Waiting for round 2')} value={ROUND2.length} icon={Users} tone="purple" hint={t('The system fills vacancies automatically')} />
      </div>

      <Tabs<TabKey>
        items={[
          { value: 'proposal', label: t('Proposal BR-SP27-02'), count: open.length },
          { value: 'round2', label: t('Round 2 & fill vacancies'), count: ROUND2.length },
        ]}
        value={tab}
        onChange={setTab}
      />

      {tab === 'proposal' && (
        <SectionCard noPadding>
          <div className="p-4 border-b border-line flex flex-col md:flex-row md:items-center gap-3 justify-between">
            <label className="flex items-center gap-2 text-xs text-ink-muted">
              <input type="checkbox" checked={onlyConflicts} onChange={(e) => setOnlyConflicts(e.target.checked)} className="accent-brand-ink" />
              {t('Only rows with warnings')}
            </label>
            <div className="relative">
              <Search className="w-4 h-4 text-ink-subtle absolute left-3 top-1/2 -translate-y-1/2" />
              <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder={t('Name, student ID, bed…')} className="pl-9 pr-3 py-2 text-xs rounded-lg border border-line w-full md:w-56" />
            </div>
          </div>
          <div className="overflow-x-auto">
            <table className="w-full text-xs">
              <thead className="bg-surface-muted text-ink-muted">
                <tr>
                  <th className="text-left font-semibold px-4 py-3">{t('Student')}</th>
                  <th className="text-left font-semibold px-4 py-3">{t('Room type')}</th>
                  <th className="text-left font-semibold px-4 py-3">{t('Group')}</th>
                  <th className="text-left font-semibold px-4 py-3">{t('Proposed bed')}</th>
                  <th className="text-left font-semibold px-4 py-3">{t('Warning')}</th>
                  <th className="text-left font-semibold px-4 py-3">{t('Adjust')}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-line">
                {visible.map((r) => (
                  <tr key={r.id} className={clsx(r.conflict && !r.adjusted && 'bg-rose-50/40')}>
                    <td className="px-4 py-3"><div className="font-semibold text-ink">{r.name}</div><div className="text-label text-ink-subtle">{r.id} · {t(r.gender)}</div></td>
                    <td className="px-4 py-3">{r.roomType}</td>
                    <td className="px-4 py-3">{r.group ?? '—'}</td>
                    <td className="px-4 py-3 font-bold">{r.adjusted ? <><span className="line-through text-ink-subtle mr-1">{r.bed}</span><span className="text-emerald-700">{r.adjusted}</span></> : r.bed}</td>
                    <td className="px-4 py-3">
                      {r.conflict ? (
                        <span className={clsx('inline-flex items-center gap-1 font-semibold', r.adjusted ? 'text-emerald-600' : 'text-rose-600')}>
                          {r.adjusted ? <CheckCircle2 className="w-3.5 h-3.5" /> : <AlertTriangle className="w-3.5 h-3.5" />}
                          {r.adjusted ? t('Resolved') : CONFLICT_LABEL[r.conflict]}
                        </span>
                      ) : (
                        <span className="text-ink-subtle">—</span>
                      )}
                    </td>
                    <td className="px-4 py-3">
                      {r.adjusted ? (
                        <button type="button" onClick={() => undo(r.id)} className="text-ink-muted hover:text-rose-600 inline-flex items-center gap-1"><Undo2 className="w-3.5 h-3.5" />{t('Undo')}</button>
                      ) : (
                        <select
                          disabled={status !== 'DRAFT'}
                          defaultValue=""
                          onChange={(e) => e.target.value && adjust(r.id, e.target.value)}
                          className="px-2 py-1 text-xs border border-line rounded-md bg-surface"
                        >
                          <option value="">{t('Move to bed…')}</option>
                          {FREE_BEDS[r.gender].map((b) => <option key={b} value={b}>{b}</option>)}
                        </select>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="px-4 py-3 border-t text-label text-ink-muted">
            {t('Showing')} {visible.length} {t('sample rows. Rows without warnings keep the algorithm\'s result.')}
          </div>
        </SectionCard>
      )}

      {tab === 'round2' && (
        <SectionCard title={t('Students waiting for round 2')} subtitle={t('The system opens round 2 on 02/12 and fills beds freed by no-shows / cancellations')} noPadding>
          <ul className="divide-y divide-line">
            {ROUND2.map((s) => (
              <li key={s.id} className="px-5 py-3 flex items-center gap-3 text-xs">
                <div className="flex-1">
                  <div className="font-semibold text-ink">{s.name} <span className="text-ink-subtle font-normal">{s.id}</span></div>
                  <div className="text-ink-muted">{s.roomType} · {s.reason}</div>
                </div>
                {s.accepted ? <StatusBadge status="WAITING_NEXT_ROUND" customLabel={t('Accepted round 2')} /> : <StatusBadge status="PENDING" customLabel={t('No response')} />}
              </li>
            ))}
          </ul>
          <div className="px-5 py-3 border-t text-label text-ink-muted flex items-center gap-1.5"><Clock className="w-3.5 h-3.5" />{t('Students who decline round 2 will have their application cancelled and deposit refunded.')}</div>
        </SectionCard>
      )}

      <Modal
        open={sendOpen}
        onClose={() => setSendOpen(false)}
        title={t('Send proposal BR-SP27-02 to the manager')}
        footer={
          <>
            <AppButton variant="outline" onClick={() => setSendOpen(false)}>{t('Cancel')}</AppButton>
            <AppButton onClick={() => { setStatus('PENDING_APPROVAL'); setSendOpen(false); show(t('Proposal sent — waiting for manager approval')); }}>{t('Submit for approval')}</AppButton>
          </>
        }
      >
        <div className="space-y-3 text-xs">
          <p className="text-ink-muted">{rows.filter((r) => r.adjusted).length} {t('allocations adjusted manually; 0 conflicts remaining.')}</p>
          <label className="font-semibold text-ink flex items-center gap-1.5"><MessageSquare className="w-3.5 h-3.5" />{t('Note for the manager')}</label>
          <textarea value={note} onChange={(e) => setNote(e.target.value)} rows={3} className="w-full px-3 py-2 border border-line rounded-lg" placeholder={t('E.g. Moved 2 students to the correct gender zone…')} />
        </div>
      </Modal>

      {toastNode}
    </div>
  );
}
